-- =========================================================
-- 1. CARGO
-- =========================================================

CREATE TABLE cargo (
    id_cargo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cargo VARCHAR NOT NULL UNIQUE,
    descricao TEXT,
    nivel_acesso INT
);


-- =========================================================
-- 2. PERIODO
-- =========================================================

CREATE TABLE periodo (
    id_periodo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_periodo VARCHAR NOT NULL,
    ano_letivo INT NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,

    CONSTRAINT chk_periodo_datas
        CHECK (data_fim >= data_inicio)
);


-- =========================================================
-- 3. CURSO
-- =========================================================

CREATE TABLE curso (
    id_curso INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_curso VARCHAR NOT NULL UNIQUE,
    descricao TEXT,
    carga_horaria INT NOT NULL,
    status VARCHAR NOT NULL DEFAULT 'ativo',

    CONSTRAINT chk_curso_carga_horaria
        CHECK (carga_horaria > 0)
);


-- =========================================================
-- 4. DISCIPLINA
-- =========================================================

CREATE TABLE disciplina (
    id_disciplina INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_disciplina VARCHAR NOT NULL UNIQUE,
    descricao TEXT,
    carga_horaria INT NOT NULL,

    CONSTRAINT chk_disciplina_carga_horaria
        CHECK (carga_horaria > 0)
);


-- =========================================================
-- 5. USUARIO
-- Integração com Supabase Auth
-- =========================================================

CREATE TABLE usuario (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID NOT NULL UNIQUE,
    email VARCHAR NOT NULL UNIQUE,
    id_cargo INT NOT NULL,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acesso TIMESTAMP,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_usuario_auth
        FOREIGN KEY (auth_user_id)
        REFERENCES auth.users(id),

    CONSTRAINT fk_usuario_cargo
        FOREIGN KEY (id_cargo)
        REFERENCES cargo(id_cargo)
);


-- =========================================================
-- 6. TURMA
-- =========================================================

CREATE TABLE turma (
    id_turma INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso INT NOT NULL,
    id_periodo INT NOT NULL,
    nome_turma VARCHAR NOT NULL,
    turno VARCHAR NOT NULL,

    CONSTRAINT fk_turma_curso
        FOREIGN KEY (id_curso)
        REFERENCES curso(id_curso),

    CONSTRAINT fk_turma_periodo
        FOREIGN KEY (id_periodo)
        REFERENCES periodo(id_periodo)
);


-- =========================================================
-- 7. COORDENADOR
-- =========================================================

CREATE TABLE coordenador (
    id_coordenador INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL UNIQUE,
    nome_completo VARCHAR NOT NULL,
    escopo_responsabilidade VARCHAR,

    CONSTRAINT fk_coordenador_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
);


-- =========================================================
-- 8. ALUNO
-- =========================================================

CREATE TABLE aluno (
    id_aluno INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL UNIQUE,
    nome_completo VARCHAR NOT NULL,
    data_nascimento DATE NOT NULL,
    data_ingresso DATE NOT NULL,
    matricula_escolar VARCHAR NOT NULL UNIQUE,

    CONSTRAINT fk_aluno_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario),

    CONSTRAINT chk_aluno_data_ingresso
        CHECK (data_ingresso >= data_nascimento)
);


-- =========================================================
-- 9. PROFESSOR
-- =========================================================

CREATE TABLE professor (
    id_professor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL UNIQUE,
    nome_completo VARCHAR NOT NULL,
    data_contratacao DATE,
    formacao VARCHAR,

    CONSTRAINT fk_professor_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
);


-- =========================================================
-- 10. AUDITORIA
-- =========================================================

CREATE TABLE auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT,
    tabela_modificada VARCHAR NOT NULL,
    operacao VARCHAR NOT NULL,
    dados_anteriores JSONB,
    dados_novos JSONB,
    "timestamp" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    endereco_ip VARCHAR,

    CONSTRAINT fk_auditoria_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
);


-- =========================================================
-- 11. DISCIPLINA_TURMA
-- =========================================================

CREATE TABLE disciplina_turma (
    id_disciplina_turma INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_disciplina INT NOT NULL,
    id_turma INT NOT NULL,

    CONSTRAINT fk_disciplina_turma_disciplina
        FOREIGN KEY (id_disciplina)
        REFERENCES disciplina(id_disciplina),

    CONSTRAINT fk_disciplina_turma_turma
        FOREIGN KEY (id_turma)
        REFERENCES turma(id_turma),

    CONSTRAINT uk_disciplina_turma
        UNIQUE (id_disciplina, id_turma)
);


-- =========================================================
-- 12. MATRICULA
-- =========================================================

CREATE TABLE matricula (
    id_matricula INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno INT NOT NULL,
    id_turma INT NOT NULL,
    data_matricula DATE NOT NULL DEFAULT CURRENT_DATE,
    data_desligamento DATE,
    status VARCHAR NOT NULL DEFAULT 'ativa',

    CONSTRAINT fk_matricula_aluno
        FOREIGN KEY (id_aluno)
        REFERENCES aluno(id_aluno),

    CONSTRAINT fk_matricula_turma
        FOREIGN KEY (id_turma)
        REFERENCES turma(id_turma),

    CONSTRAINT chk_matricula_datas
        CHECK (
            data_desligamento IS NULL
            OR data_desligamento >= data_matricula
        )
);


-- =========================================================
-- 13. COMENTARIO
-- =========================================================

CREATE TABLE comentario (
    id_comentario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno INT,
    id_professor INT,
    id_disciplina_turma INT NOT NULL,
    titulo VARCHAR NOT NULL,
    tipo VARCHAR,
    classificacao VARCHAR,
    descricao TEXT NOT NULL,
    data_comentario TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_comentario_aluno
        FOREIGN KEY (id_aluno)
        REFERENCES aluno(id_aluno),

    CONSTRAINT fk_comentario_professor
        FOREIGN KEY (id_professor)
        REFERENCES professor(id_professor),

    CONSTRAINT fk_comentario_disciplina_turma
        FOREIGN KEY (id_disciplina_turma)
        REFERENCES disciplina_turma(id_disciplina_turma),

    CONSTRAINT chk_comentario_autor
        CHECK (
            id_aluno IS NOT NULL
            OR id_professor IS NOT NULL
        )
);


-- =========================================================
-- 14. AVALIACAO
-- =========================================================

CREATE TABLE avaliacao (
    id_avaliacao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_disciplina_turma INT NOT NULL,
    id_professor INT NOT NULL,
    id_periodo INT NOT NULL,
    nome_avaliacao VARCHAR NOT NULL,
    tipo_avaliacao VARCHAR,
    data_avaliacao DATE NOT NULL,
    valor_total NUMERIC(10,2) NOT NULL,
    peso NUMERIC(10,2) NOT NULL,
    status VARCHAR NOT NULL DEFAULT 'ativa',

    CONSTRAINT fk_avaliacao_disciplina_turma
        FOREIGN KEY (id_disciplina_turma)
        REFERENCES disciplina_turma(id_disciplina_turma),

    CONSTRAINT fk_avaliacao_professor
        FOREIGN KEY (id_professor)
        REFERENCES professor(id_professor),

    CONSTRAINT fk_avaliacao_periodo
        FOREIGN KEY (id_periodo)
        REFERENCES periodo(id_periodo),

    CONSTRAINT chk_avaliacao_valor
        CHECK (valor_total > 0),

    CONSTRAINT chk_avaliacao_peso
        CHECK (peso > 0)
);


-- =========================================================
-- 15. AULA
-- =========================================================

CREATE TABLE aula (
    id_aula INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_disciplina_turma INT NOT NULL,
    id_professor INT NOT NULL,
    data_aula DATE NOT NULL,
    horario_inicio TIME NOT NULL,
    horario_fim TIME NOT NULL,
    conteudo TEXT,
    status VARCHAR NOT NULL DEFAULT 'programada',

    CONSTRAINT fk_aula_disciplina_turma
        FOREIGN KEY (id_disciplina_turma)
        REFERENCES disciplina_turma(id_disciplina_turma),

    CONSTRAINT fk_aula_professor
        FOREIGN KEY (id_professor)
        REFERENCES professor(id_professor),

    CONSTRAINT chk_aula_horarios
        CHECK (horario_fim > horario_inicio)
);


-- =========================================================
-- 16. ALUNO_AVALIACAO
-- =========================================================

CREATE TABLE aluno_avaliacao (
    id_aluno_avaliacao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno INT NOT NULL,
    id_avaliacao INT NOT NULL,
    nota NUMERIC(10,2) NOT NULL,
    observacao TEXT,
    data_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_aluno_avaliacao_aluno
        FOREIGN KEY (id_aluno)
        REFERENCES aluno(id_aluno),

    CONSTRAINT fk_aluno_avaliacao_avaliacao
        FOREIGN KEY (id_avaliacao)
        REFERENCES avaliacao(id_avaliacao),

    CONSTRAINT uk_aluno_avaliacao
        UNIQUE (id_aluno, id_avaliacao),

    CONSTRAINT chk_aluno_avaliacao_nota
        CHECK (nota >= 0)
);


-- =========================================================
-- 17. FREQUENCIA
-- =========================================================

CREATE TABLE frequencia (
    id_frequencia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aula INT NOT NULL,
    id_aluno INT NOT NULL,
    presente BOOLEAN NOT NULL,
    justificativa TEXT,
    data_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_frequencia_aula
        FOREIGN KEY (id_aula)
        REFERENCES aula(id_aula),

    CONSTRAINT fk_frequencia_aluno
        FOREIGN KEY (id_aluno)
        REFERENCES aluno(id_aluno),

    CONSTRAINT uk_frequencia_aluno_aula
        UNIQUE (id_aula, id_aluno)
);


